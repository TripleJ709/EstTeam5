import Foundation

extension Emotion {
    var weeklyFeedback: String? {
        switch self {
        case .joy: "이번 주는 웃음과 기쁨이 가득했구나. 이 순간을 마음껏 누리고 행복을 온전히 만끽해 줘."
        case .achievement : "이번 주는 해낸 일이 많았구나. 그 만큼 애쓴 나를 충분히 칭찬해줘"
        case .stable : "이번 주는 마음이 참 잔잔하고 평온했구나. 일상의 균형을 잘 지켜낸 나에게 고마워해 줘"
        case .angry : "이번 주는 화가 나고 억울한 일이 많았구나. 내 마음을 지키려 애쓴 나를 먼저 따뜻하게 토닥여 줘."
        case .fear : "이번 주는 앞날이 막막하고 불안했구나. 두려움 속에서도 오늘까지 잘 버텨준 나를 꼭 안아 줘."
        case .sad : "이번 주는 마음이 시리고 눈물 나는 일이 있었구나. 슬픔을 억누르지 말고 내 마음을 가만히 위로해 줘."
        case .exhausted : "이번 주는 몸도 마음도 참 많이 지쳤구나. 그동안 치열하게 달려온 나에게 이제는 온전한 쉼을 선물해 줘."
        }
    }
    
    var monthlyFeedback : String? {
        switch self {
        case .joy: "이번 달은 유독 반짝이는 기쁨이 많았구나. 일상의 행복을 놓치지 않고 잘 발견해 낸 나에게 고마워하고, 이 따뜻한 에너지를 마음 깊숙이 저장해 줘."
        case .achievement : "이번 달은 묵묵히 해낸 일들이 참 많았구나. 한 걸음씩 성실하게 쌓아 올린 나의 시간들을 자랑스러워하고 스스로에게 큰 박수를 보내 줘."
        case .stable : "이번 달은 큰 흔들림 없이 잔잔하고 평온했구나. 내 삶의 중심과 일상의 단단한 균형을 잘 지켜낸 나 자신을 아낌없이 칭찬해 줘."
        case .angry : "이번 달은 유독 화가 나고 마음 상하는 일이 잦았구나. 오랫동안 내 선을 지키려 고군분투한 나를 토닥여 주고, 이제 내 마음이 진짜 원하는 게 무엇인지 귀 기울여 줘."
        case .fear : "이번 달은 다가올 일들로 마음이 많이 흔들리고 불안했구나. 길었던 두려움 속에서도 도망치지 않고 하루하루를 살아낸 나의 용기를 꼭 인정해 줘."
        case .sad : "이번 달은 마음 한편이 시리고 슬픈 날이 길었구나. 아픈 계절을 지나오느라 고생한 나를 따뜻하게 안아 주고, 충분히 슬퍼할 시간을 허락해 줘."
        case .exhausted : "이번 달은 에너지가 바닥날 만큼 쉼 없이 달려왔구나. 한 달 내내 버텨낸 것만으로도 충분히 잘했으니, 이제는 모든 짐을 잠시 내려놓고 나를 먼저 돌봐 줘."
        }
    }
}
